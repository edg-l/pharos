//! Electra epoch processing.
//!
//! Per `specs/electra/beacon-chain.md` Epoch processing (`:878-898`).
//!
//! Electra (EIP-7251) reshapes five steps and adds two new ones. The five
//! electra-native steps (`process_registry_updates`, `process_slashings`,
//! `process_pending_deposits`, `process_pending_consolidations`,
//! `process_effective_balance_updates`) plus `process_sync_committee_updates`
//! (which uses the modified `get_next_sync_committee_indices`) operate on the
//! concrete electra state directly. The unchanged steps
//! (`process_justification_and_finalization`, `process_inactivity_updates`,
//! `process_rewards_and_penalties`, `process_eth1_data_reset`,
//! `process_slashings_reset`, `process_randao_mixes_reset`,
//! `process_historical_summaries_update`, `process_participation_flag_updates`)
//! delegate to the deneb/capella/altair siblings via the electra↔deneb state
//! projection.

pub mod effective_balance_updates;
